import assert from "node:assert/strict";
import fs from "node:fs";
import { createRequire } from "node:module";
import ts from "typescript";
const require = createRequire(import.meta.url);
require.extensions[".ts"] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { seed } = require("../src/features/hr/seed.ts");
const { validHrData } = require("../src/features/hr/schemas/validation.ts");
const { attendanceAt, leaveBalance, workforce } = require("../src/features/hr/selectors.ts");
const { payrollTotals, workHours, today } = require("../src/features/hr/types.ts");
const { hrStore, saveEmployee, deleteEmployee, saveAttendance, requestLeave, decideLeave, moveCandidate, scheduleInterview, updatePayroll } = require("../src/features/hr/demo-service.ts");
globalThis.localStorage = { setItem() {}, getItem() { return null; } };
const state = () => hrStore.getSnapshot().data;
assert.equal(validHrData(seed), true);
assert.equal(validHrData({ ...seed, attendance: [{ ...seed.attendance[0], employeeId: "missing" }] }), false);
assert.equal(validHrData({ ...seed, payroll: [{ ...seed.payroll[0], deductions: 999999 }] }), false);
assert.equal(payrollTotals({ base: 1000, allowances: 250, deductions: 100 }).net, 1150);
assert.deepEqual(workHours({ status: "Present", clockIn: "09:00", clockOut: "19:00", breakMinutes: 60 }), { hours: 9, overtime: 1 });
const view = workforce(seed, "all", 30); assert.equal(view.opening.length + view.hires.length - view.departures.length, view.now.length);
const person = seed.employees.find(e => e.id === "EMP-106");
const balance = leaveBalance(state(), person.id, "Sick").remaining;
assert.equal(decideLeave("LV-103", "Approved", "Verified coverage"), "");
assert.equal(attendanceAt(state(), person, today).status, "On leave");
assert.equal(leaveBalance(state(), person.id, "Sick").remaining, balance - 1);
assert.match(decideLeave("LV-103", "Rejected", "Changed decision"), /Only pending/);
assert.match(saveAttendance({ id: "", employeeId: person.id, date: today, status: "Present", clockIn: "09:00", clockOut: "18:00", breakMinutes: 60, reason: "Cannot override leave" }), /Approved leave/);
assert.match(requestLeave({ id: "", employeeId: "EMP-105", type: "Annual", start: "2026-11-05", end: "2026-11-06", reason: "Overlap", status: "Pending", created: today, decision: "" }), /overlap/);
assert.match(requestLeave({ id: "", employeeId: "EMP-101", type: "Annual", start: "2026-11-03", end: "2026-12-15", reason: "Too many days", status: "Pending", created: today, decision: "" }), /remaining/);
assert.match(saveEmployee({ ...seed.employees[0], managerId: "EMP-105" }), /cycle/);
assert.match(deleteEmployee("EMP-101"), /Referenced/);
assert.equal(saveEmployee({ ...seed.employees[0], id: "", managerId: "", name: "New Demo", email: "new-demo@example.com" }), "");
const added = state().employees.find(e => e.email === "new-demo@example.com"); assert.ok(added);
assert.equal(deleteEmployee(added.id), ""); assert.equal(state().employees.some(e => e.id === added.id), false);
assert.match(moveCandidate("CAN-101", "Offer"), /one stage/);
assert.equal(moveCandidate("CAN-101", "Screening"), "");
assert.equal(scheduleInterview({ id: "", candidateId: "CAN-101", employeeId: "EMP-101", date: "2026-11-05", time: "11:00", note: "Verified", status: "Scheduled" }), "");
assert.equal(state().candidates.find(c => c.id === "CAN-101").stage, "Interview");
assert.match(scheduleInterview({ id: "", candidateId: "CAN-101", employeeId: "EMP-101", date: "2026-11-05", time: "11:00", note: "Duplicate", status: "Scheduled" }), /already has/);
const payroll = state().payroll.find(p => p.period === "2026-11");
assert.match(updatePayroll(payroll.id, "Paid"), /Draft to Reviewed/);
assert.equal(updatePayroll(payroll.id, "Reviewed"), ""); assert.equal(updatePayroll(payroll.id, "Paid"), "");
assert.equal(state().payroll.find(p => p.id === payroll.id).paidOn, today);
assert.equal(validHrData(state()), true);
console.log("PASS HR references, headcount reconciliation, hours/overtime, leave balance/attendance linkage, overlap guards, manager cycles, safe deletion, hiring transitions/conflicts and payroll arithmetic/status sequence");
