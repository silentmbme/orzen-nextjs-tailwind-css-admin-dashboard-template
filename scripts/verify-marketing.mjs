import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts/marketing', { recursive: true });
const base = process.env.BASE_URL ?? 'http://localhost:3000';
const browser = await chromium.launch({ channel: 'chrome' });
const errors = [];
const page = await browser.newPage();
page.setDefaultTimeout(15000);
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
try {
  const titles = new Set();
  for (const theme of ['light', 'dark']) for (const width of [320, 390, 768, 1440]) for (const kind of ['saas', 'ai', 'crm', 'ecommerce']) {
    await page.setViewportSize({ width, height: 950 });
    await page.goto(`${base}/landing/${kind}`);
    await page.evaluate(value => { localStorage.setItem('theme', value); localStorage.removeItem('orzen-layout'); }, theme);
    await page.reload();
    await page.locator('main h1').waitFor();
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(250);
    assert.equal(await page.locator('h1').count(), 1);
    assert.equal(await page.locator('.sidebar,.topbar').count(), 0);
    if (width < 640) assert.equal(await page.locator('header').getByRole('link', { name: 'Explore demo', exact: true }).isVisible(), false);
    assert.ok(await page.locator('meta[name="description"]').getAttribute('content'));
    assert.ok(await page.locator('meta[property="og:title"]').getAttribute('content'));
    assert.equal(await page.locator('html').getAttribute('class'), theme);
    const overflow = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
    assert.ok(overflow.scroll <= overflow.width, `${kind}/${theme}/${width}: ${JSON.stringify(overflow)}`);
    titles.add(await page.title());
    await page.screenshot({ path: `artifacts/marketing/${kind}-${theme}-${width}.png`, fullPage: width === 1440 || width === 390 });
  }
  assert.equal(titles.size, 4);
  await page.setViewportSize({ width: 1440, height: 950 });
  await page.goto(`${base}/landing/saas`);
  await page.getByRole('combobox', { name: 'Marketing revenue window' }).selectOption('90');
  await page.locator('#revenue .ui-card__header').getByText('Last 90 days', { exact: true }).waitFor();
  const billing = page.getByRole('group', { name: 'Billing period' });
  await billing.getByRole('button', { name: 'Yearly', exact: true }).click();
  await page.getByText('$790 billed yearly', { exact: true }).waitFor();
  await billing.getByRole('button', { name: 'Monthly', exact: true }).click();
  const question = page.locator('summary').first();
  await question.click();
  assert.ok(await question.locator('..').getAttribute('open') !== null);
  await page.goto(`${base}/landing/ai`);
  await page.getByRole('textbox', { name: 'Demo AI prompt' }).fill('Improve support');
  await page.getByRole('button', { name: 'Send demo prompt' }).click();
  await page.getByText(/Demo plan: group incoming questions/).waitFor();
  await page.getByRole('combobox', { name: 'Preview AI model' }).selectOption('Lumen Write');
  await page.getByRole('combobox', { name: 'Demo workflow' }).selectOption('Document briefing');
  await page.getByRole('button', { name: 'Run simulation' }).click();
  await page.getByText('Demo complete. No external task was executed.', { exact: true }).waitFor();
  await page.goto(`${base}/landing/crm`);
  await page.getByRole('button', { name: /Northline expansion/ }).click();
  const deal = page.getByRole('dialog', { name: 'Deal preview', exact: true });
  await deal.getByRole('button', { name: 'Move to Qualified', exact: true }).click();
  await deal.getByRole('button', { name: 'Move to Proposal', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Reset pipeline', exact: true }).click();
  const lead = page.locator('#contact form');
  assert.equal(await lead.evaluate(form => form.checkValidity()), false);
  await lead.getByRole('textbox', { name: 'Full name', exact: true }).fill('Jamie Lee');
  await lead.getByRole('textbox', { name: 'Company', exact: true }).fill('Demo Studio');
  await lead.getByRole('textbox', { name: 'Work email', exact: true }).fill('jamie@example.com');
  await lead.getByRole('checkbox').check();
  await lead.getByRole('button', { name: 'Request a demo consultation' }).click();
  await lead.getByRole('status').waitFor();
  await page.goto(`${base}/landing/ecommerce`);
  const products = page.locator('#products');
  assert.equal(await products.locator('article').count(), 4);
  await page.getByRole('textbox', { name: 'Search store products' }).fill('watch');
  assert.equal(await products.locator('article').count(), 1);
  await page.getByRole('textbox', { name: 'Search store products' }).fill('not-a-product');
  await products.getByText('Nothing here just yet.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Show all products', exact: true }).click();
  const card = products.locator('article').first();
  await card.getByRole('button', { name: /to wishlist$/ }).click();
  await page.getByRole('button', { name: 'Wishlist (1)', exact: true }).click();
  assert.equal(await products.locator('article').count(), 1);
  await page.getByRole('button', { name: 'Wishlist (1)', exact: true }).click();
  await card.getByRole('button', { name: /Quick view Studio wireless headphones/ }).click();
  const quick = page.getByRole('dialog', { name: 'Product quick view', exact: true });
  await quick.getByRole('button', { name: 'Add to demo bag', exact: true }).click();
  await page.getByRole('button', { name: 'Bag (1)', exact: true }).click();
  const bag = page.getByRole('dialog', { name: 'Your shopping bag', exact: true });
  await bag.getByRole('button', { name: 'Increase Studio wireless headphones', exact: true }).click();
  assert.ok((await bag.innerText()).includes('$258'));
  await bag.getByRole('button', { name: 'Remove Studio wireless headphones', exact: true }).click();
  await bag.getByText('Your demo bag is empty.', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  const newsletter = page.locator('form').filter({ has: page.getByRole('button', { name: 'Join the demo list' }) });
  await newsletter.getByRole('textbox', { name: 'Email address' }).fill('reader@example.com');
  await newsletter.getByRole('checkbox').check();
  await newsletter.getByRole('button', { name: 'Join the demo list' }).click();
  await newsletter.getByRole('status').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open marketing menu', exact: true }).click();
  await page.locator('#marketing-mobile-menu').getByRole('link', { name: 'CRM', exact: true }).click();
  await page.waitForURL(`${base}/landing/crm`);
  await page.getByRole('button', { name: 'Switch marketing theme', exact: true }).click();
  const selectedTheme = await page.locator('html').getAttribute('class');
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('class'), selectedTheme);
  const links = new Set();
  for (const kind of ['saas', 'ai', 'crm', 'ecommerce']) {
    await page.goto(`${base}/landing/${kind}`);
    for (const href of await page.locator('a[href^="#"]').evaluateAll(nodes => nodes.map(node => node.getAttribute('href')))) assert.equal(await page.locator(href).count(), 1, `Missing anchor ${href}`);
    for (const href of await page.locator('a[href^="/"]').evaluateAll(nodes => nodes.map(node => node.getAttribute('href')))) links.add(href);
  }
  for (const href of links) assert.ok((await page.request.get(`${base}${href}`)).ok(), `Broken link ${href}`);
  assert.deepEqual(errors, []);
  console.log('PASS marketing: 32 responsive/theme cases, metadata, navigation, pricing, FAQ, AI simulations, pipeline, forms, search, wishlist, quick view and bag');
} finally { await browser.close(); }
