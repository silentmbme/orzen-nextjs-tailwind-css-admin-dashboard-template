import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import ts from 'typescript';
const require = createRequire(import.meta.url);
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { seed } = require('../src/features/ai/seed.ts');
const { validAiData, variables } = require('../src/features/ai/schemas/validation.ts');
const { metrics, scopedRequests, requestCost } = require('../src/features/ai/types.ts');
const { aiStore, savePrompt, deletePrompt, saveWorkflow, startRun, stopRun, sendChat } = require('../src/features/ai/demo-service.ts');
globalThis.localStorage = { setItem(){}, getItem(){return null} };
const state = () => aiStore.getSnapshot().data;
assert.equal(validAiData(seed), true);
assert.equal(validAiData({ ...seed, requests: [{ ...seed.requests[0], modelId: 'missing' }] }), false);
assert.equal(validAiData({ ...seed, defaultModelId: 'prism-vision' }), false);
assert.deepEqual(variables('{{topic}} {{ topic }} {{audience}}'), ['topic','audience']);
const m = metrics(seed.requests, seed.models);
assert.equal(m.total, m.success + m.errors);
assert.equal(m.input + m.output, seed.requests.reduce((sum,r) => sum+r.input+r.output, 0));
assert.equal(m.cost, seed.requests.reduce((sum,r) => sum+requestCost(r,seed.models), 0));
assert.ok(scopedRequests(seed,{environment:'Sandbox',modelId:'nova-core',from:'2026-11-01',to:'2026-11-02'}).every(r=>r.environment==='Sandbox'&&r.modelId==='nova-core'&&r.time>='2026-11-01'));
assert.match(deletePrompt('prompt-summary'), /referenced/);
const prompt = {...seed.prompts[0], id:'test-prompt', name:'Domain prompt', versions:[]};
assert.equal(savePrompt(prompt), '');
assert.equal(savePrompt({...prompt,content:'Updated {{topic}}'}), '');
assert.equal(state().prompts.find(p=>p.id===prompt.id).versions.length, 1);
assert.equal(deletePrompt(prompt.id), '');
assert.notEqual(saveWorkflow({...seed.workflows[0],modelId:'prism-vision'}), '');
assert.notEqual(startRun('flow-review',false), '');
const before=state().requests.length;
assert.equal(startRun('flow-brief',false),'');
assert.notEqual(startRun('flow-brief',false),'');
await new Promise(r=>setTimeout(r,1200));
assert.equal(state().runs[0].status,'Succeeded');
assert.equal(state().requests.length,before+1);
assert.equal(startRun('flow-brief',true),'');
await new Promise(r=>setTimeout(r,1200));
assert.equal(state().runs[0].status,'Failed');
assert.equal(state().requests[0].output,0);
assert.equal(startRun('flow-brief',false),'');
assert.equal(stopRun('flow-brief'),'');
await new Promise(r=>setTimeout(r,1200));
assert.equal(state().runs[0].detail,'Simulation stopped locally. You can start a new run.');
assert.equal(await sendChat('chat-welcome','Summarize a project'), '');
const count=state().conversations[0].messages.length;
assert.equal(await sendChat('chat-welcome','',true),'');
assert.equal(state().conversations[0].messages.length,count);
assert.equal(state().requests[0].source,'Chat');
assert.equal(validAiData(state()),true);
globalThis.localStorage.setItem = () => { throw new Error('Simulated quota failure'); };
assert.equal(aiStore.update(data => { data.prompts[0].favorite = !data.prompts[0].favorite; }), '');
assert.match(aiStore.getSnapshot().warning, /Storage is unavailable or full/);
assert.equal(validAiData(state()),true);
console.log('PASS AI relations, aggregate arithmetic, scope filters, prompt variables/history/reference guards, workflow success/failure/stop/concurrency and deterministic chat regeneration');
